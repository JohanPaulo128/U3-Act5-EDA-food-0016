import pandas as pd
import matplotlib.pyplot as plt
# Johan Paulo Aros Reveles
# 1. Leer el archivo CSV comida pais India
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEÍDOS DESDE CSV 0016 ---")
print(df_food_india)
print("\n--- Mostrando nomre, comida + ingrdientes 0016 ---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- tiempo de cocinado mostrar 10 ingrdientes con head 0016 ---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n--- Grafica comida (x) Tiempo de cocinado (Y) 0016 ---")
print("\n--- Grafica comida (x) texto a 30 grados 0016 ---")
nombre_y_hora.plot.bar(x='name',y='cook_time', rot=30)
plt.title('Comida tipica de India Johan 0016')
plt.xlabel('Nombre de platillo')
plt.ylabel('Tiempo de cocinado')
plt.show()
name_and_time = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
name_and_time.plot.bar(x='name', rot=30)
plt.title('Grafica de 2 columnas Johan 0016')
plt.xlabel('Nombre de platillo')
plt.ylabel('Tiempo de cocinado Prep y comida')
plt.show()
print("\n--- Grafica apiladas verticalmente una tras otra verticalmente Johan 0016 ---")
name_and_time.plot.bar(x='name', stacked=True)
plt.title('Grafica apiladas Johan 0016')
plt.xlabel('Nombre de platillo')
plt.ylabel('Tiempo de cocinado Prep y comida')
plt.show()
